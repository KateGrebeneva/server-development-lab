from datetime import datetime
from typing import Protocol

from internal.domain import StudySession, Subject, Task, User

class UserRepository(Protocol):
    async def create(self, user: User) -> User: ...

    async def get_by_id(self, user_id: int) -> User: ...

    async def get_by_email(self, email: str) -> User: ...

    async def list(self, limit: int = 20, offset: int = 0) -> list[User]: ...

    async def delete(self, user_id: int) -> None: ...

    async def lock(self, user_id: int) -> None: ...


class SubjectRepository(Protocol):
    async def create(self, subject: Subject) -> Subject: ...

    async def get_by_id(self, subject_id: int) -> Subject: ...

    async def list(self, limit: int = 20, offset: int = 0) -> list[Subject]: ...

    async def update(self, subject: Subject) -> Subject: ...

    async def delete(self, subject_id: int) -> None: ...


class TaskRepository(Protocol):
    async def create(self, task: Task) -> Task: ...

    async def get_by_id(self, task_id: int) -> Task: ...

    async def list(self, limit: int = 20, offset: int = 0) -> list[Task]: ...

    async def update(self, task: Task) -> Task: ...

    async def delete(self, task_id: int) -> None: ...


class StudySessionRepository(Protocol):
    async def create(self, session: StudySession) -> StudySession: ...

    async def get_by_id(self, session_id: int) -> StudySession: ...

    async def list(self, limit: int = 20, offset: int = 0) -> list[StudySession]: ...

    async def delete(self, session_id: int) -> None: ...

    async def has_overlap(self, user_id: int, start: datetime, end: datetime) -> bool: ...
